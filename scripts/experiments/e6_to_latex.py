"""
E6 -> LaTeX. Writes manuscript_rse/sections/supp_tab_e6_parity.tex (Supplementary Table S4 body)
and prints the Table 2 row group (main text) with the same rounding rules as Table 2.
Sources: outputs_dual/benchmarks/E6_headline_D01_definitions.csv, E6_paired_production_vs_dual.csv
"""
import os
import pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
B = os.path.join(ROOT, 'outputs_dual', 'benchmarks')
H = pd.read_csv(os.path.join(B, 'E6_headline_D01_definitions.csv'))
P = pd.read_csv(os.path.join(B, 'E6_paired_production_vs_dual.csv'))
Q = {'OOF1': 'Q-I (OOF)', 'OOF3': 'Q-III (OOF)', 'Q2': 'Q-II (ens.)', 'Q4': 'Q-IV (ens.)'}
SL = {'aster': 'ASTER', 'hytes': 'HyTES'}


def n(x, d=3):
    s = f'{x:+.{d}f}' if True else ''
    return s.replace('+', '+').replace('-', '-')


def ci(v, lo, hi, sig, d=3):
    core = f'{v:+.{d}f}'.replace('-', '-')
    core = f'$\\mathbf{{{core}}}$' if sig else f'${core}$'
    return f'{core} [${lo:+.{d}f}$, ${hi:+.{d}f}$]'


def pct(v, sig):
    s = f'{v:+.1f}\\%'
    return f'$\\mathbf{{{s}}}$' if sig else f'${s}$'


# ---- Table 2 row group (OOF only, HyTES first as in Table 2)
print('% Table 2 row group: PINN with TES inputs (dual), OOF partitions')
for s in ['hytes', 'aster']:
    for i, part in enumerate(['OOF1', 'OOF3']):
        r = H[(H.sensor == s) & (H.part == part)].iloc[0]
        lab = SL[s] if i == 0 else ''
        print(f"{lab} & {Q[part]} & {r.rmse:.3f} & {r.tes_rmse:.3f} & "
              f"{ci(r.rmse - r.tes_rmse, r.dRMSE_T_lo, r.dRMSE_T_hi, r.dRMSE_T_sig)} & "
              f"{r.eps_rmse:.4f} & {r.tes_eps_rmse:.4f} & {pct(r.rel_eps_pct, r.dEps_sig)} & "
              f"{r.sam:.3f} & {r.tes_sam:.3f} \\\\")

# ---- Supplementary Table S4
L = []
L.append('\\begin{tabular}{llrrlrlrl}')
L.append('\\toprule')
L.append(' & & \\multicolumn{3}{c}{PINN-dual vs TES} & \\multicolumn{4}{c}{PINN-dual $-$ production PINN} \\\\')
L.append('\\cmidrule(lr){3-5}\\cmidrule(lr){6-9}')
L.append('Sensor & Quadrant & PINN & TES & $\\Delta$RMSE$_T$ (K) [95\\% CI] & Prod. & $\\Delta$RMSE$_T$ (K) [95\\% CI] '
         '& $\\Delta\\varepsilon$ ($10^{-3}$) & $\\Delta$SAM ($^\\circ$) [95\\% CI] \\\\')
L.append('\\midrule')
for s in ['hytes', 'aster']:
    for i, part in enumerate(['OOF1', 'OOF3', 'Q2', 'Q4']):
        r = H[(H.sensor == s) & (H.part == part)].iloc[0]
        p = P[(P.sensor == s) & (P.part == part)].iloc[0]
        lab = SL[s] if i == 0 else ''
        de = p.dEps_dual_minus_prod * 1e3
        de_s = f'{de:+.1f}'
        de_s = f'$\\mathbf{{{de_s}}}$' if p.dEps_dual_minus_prod_sig else f'${de_s}$'
        L.append(f"{lab} & {Q[part]} & {r.rmse:.3f} & {r.tes_rmse:.3f} & "
                 f"{ci(r.rmse - r.tes_rmse, r.dRMSE_T_lo, r.dRMSE_T_hi, r.dRMSE_T_sig)} & "
                 f"{p.production_mode} & "
                 f"{ci(p.dRMSE_T_dual_minus_prod, p.dRMSE_T_dual_minus_prod_lo, p.dRMSE_T_dual_minus_prod_hi, p.dRMSE_T_dual_minus_prod_sig)} & "
                 f"{de_s} & "
                 f"{ci(p.dSAM_dual_minus_prod, p.dSAM_dual_minus_prod_lo, p.dSAM_dual_minus_prod_hi, p.dSAM_dual_minus_prod_sig)} \\\\")
    if s == 'hytes':
        L.append('\\midrule')
L.append('\\bottomrule')
L.append('\\end{tabular}')
out = os.path.join(ROOT, 'manuscript', 'sections', 'supp_tab_e6_parity.tex')
with open(out, 'w', encoding='utf-8') as f:
    f.write('% Auto-generated by scripts/experiments/e6_to_latex.py from outputs_dual/benchmarks/E6_*.csv\n')
    f.write('\n'.join(L) + '\n')
print('\nwrote', out)
print('\n'.join(L))

