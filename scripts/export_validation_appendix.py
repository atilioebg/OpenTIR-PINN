"""
Appendix B generator: dataset validation protocol table
=======================================================
Source (single source of truth): data/validation/dataset_validation_report.json, written by
scripts/validate_dataset_integrity.py (TEST_CATALOG holds the test definitions).
Output: manuscript_rse/sections/appB_validation_table.tex (longtable body, 32 test IDs).

Per test ID: catalog name and acceptance rule, number of individual checks (sensor x partition x
fold), outcome counts, and the worst observed value of the gating metric (FAIL-level metric if any,
else WARN-level; worst = max for <=/</==, min for >=/>). Informative tests show the value range.
"""
import os
import re
import json
from collections import OrderedDict, Counter

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REPORT = os.path.join(ROOT, 'data', 'validation', 'dataset_validation_report.json')
OUT = os.path.join(ROOT, 'manuscript_rse', 'sections', 'appB_validation_table.tex')
ORDER = ['A0', 'A1', 'A1b', 'A2', 'A3a', 'A3b', 'A3c', 'A4', 'A5', 'A5b', 'A6',
         'B1', 'B2', 'B2b', 'B2c', 'B2d', 'B3', 'B4', 'B5', 'B6', 'B7', 'B8',
         'C1', 'C2', 'C3', 'C4', 'C5', 'C7', 'C7b', 'C8', 'C9', 'D1']
FAM = {'A': 'A. Partition integrity and leakage', 'B': 'B. Physical and numerical integrity',
       'C': 'C. Statistical design and bias', 'D': 'D. Cross-validation structure'}


def tex(s):
    s = str(s).replace('\\', '/')
    for a, b in [('&', r'\&'), ('%', r'\%'), ('#', r'\#'), ('_', r'\_'), ('{', r'\{'), ('}', r'\}'),
                 ('~', r'\textasciitilde{}'), ('^', r'\textasciicircum{}'), ('`', '')]:
        s = s.replace(a, b)
    s = s.replace('+/-', '$\\pm$')
    s = re.sub(r'>=', r'$\\geq$', s)
    s = re.sub(r'<=', r'$\\leq$', s)
    s = re.sub(r'==', r'$=$', s)
    s = re.sub(r'(?<![\\$])<', r'$<$', s)
    s = re.sub(r'(?<![\\$])>', r'$>$', s)
    s = s.replace('|', '$|$')
    return s


def fmt(v):
    if v is None:
        return '--'
    v = float(v)
    if v == int(v) and abs(v) < 1e6:
        return f'{int(v)}'
    a = abs(v)
    if a >= 100:
        return f'{v:.1f}'
    if a >= 0.01:
        return f'{v:.3g}'
    return f'{v:.1e}'.replace('e-0', 'e-')


PRIMARY = {'B4': 'max_abs_eps_minus_library', 'A6': 'duplicate_cells'}  # more informative than the first metric


def mname(name):
    return '\\texttt{' + tex(name).replace('\\_', '\\_\\allowbreak{}') + '}'


def worst(checks, test_id=None):
    ms = [m for c in checks for m in c['metrics']]
    if not ms:
        return '--'
    gated = [m for m in ms if m.get('op') not in (None, '', 'info')]
    if not gated:  # informative
        name = ms[0]['name']; vals = [m['value'] for m in ms if m['name'] == name and m['value'] is not None]
        lo, hi = min(vals), max(vals)
        rng = fmt(lo) if lo == hi else f'{fmt(lo)}--{fmt(hi)}'
        return f'{mname(name)}: {rng}'
    lvl = 'FAIL' if any(m.get('level') == 'FAIL' for m in gated) else 'WARN'
    gating = [m for m in gated if m.get('level') == lvl]
    name = PRIMARY.get(test_id, gating[0]['name'])
    sel = [m for m in gated if m['name'] == name]
    op = sel[0]['op']
    vals = [m['value'] for m in sel if m['value'] is not None]
    w = min(vals) if op in ('>=', '>') else max(vals)
    return f'{mname(name)} = {fmt(w)}'


def main():
    r = json.load(open(REPORT, encoding='utf-8'))
    by = OrderedDict((k, []) for k in ORDER)
    for x in r['results']:
        by[x['id']].append(x)
    assert set(by) == set(r['catalog']) and len(by) == 32, 'catalog / ORDER mismatch'
    L = ['% Auto-generated by scripts/export_validation_appendix.py from data/validation/dataset_validation_report.json',
         f"% Report generated {r['generated_at']} (dataset v{r['dataset_version']}); summary {r['summary']}",
         '\\begin{longtable}{@{}p{0.06\\linewidth}p{0.25\\linewidth}p{0.29\\linewidth}r p{0.11\\linewidth}p{0.20\\linewidth}@{}}',
         '\\caption{Automated dataset validation protocol (32 test IDs, ' + str(len(r['results'])) +
         ' individual checks over sensors, partitions and folds) and results for the released build (v' +
         r['dataset_version'] + '). Rules are the acceptance criteria of \\texttt{TEST\\_CATALOG}; ``Worst'' is the least '
         'favourable value of the gating metric over all checks (value range for informative tests).}'
         '\\label{tab:app_validation}\\\\',
         '\\toprule', 'ID & Test & Acceptance rule & $n$ & Outcome & Worst \\\\', '\\midrule', '\\endfirsthead',
         '\\toprule', 'ID & Test & Acceptance rule & $n$ & Outcome & Worst \\\\', '\\midrule', '\\endhead',
         '\\bottomrule', '\\endfoot']
    fam = None
    for k, checks in by.items():
        c = r['catalog'][k]
        if c['section'] != fam:
            fam = c['section']
            if fam != 'A':
                L.append('\\midrule')
            L.append(f'\\multicolumn{{6}}{{@{{}}l}}{{\\textit{{{FAM[fam]}}}}} \\\\')
        st = Counter(x['status'] for x in checks)
        outcome = ', '.join(f'{st[s]} {s}' for s in ['PASS', 'WARN', 'FAIL', 'INFO'] if st[s])
        L.append(f"{k} & {tex(c['name'])} & {tex(c['rule'])} & {len(checks)} & {outcome} & {worst(checks, k)} \\\\")
    L.append('\\end{longtable}')
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write('\n'.join(L) + '\n')
    tot = Counter(x['status'] for x in r['results'])
    print('wrote', OUT, '| checks:', len(r['results']), dict(tot))
    print('\n'.join(L[14:]))


if __name__ == '__main__':
    main()
