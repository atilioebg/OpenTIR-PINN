"""
Full hyperparameter set of every nested-LOCO (B1v2) model, for the Supplement.

Source: outputs/benchmarks/loco_b1v2/optuna_{sensor}_{class}.csv (complete Optuna ledger of each
nested study). The selected trial is the one recorded in loco_b1v2_master.csv (best_trial); the
script asserts that its objective and the 8 configuration fields duplicated in the master agree.
Outputs: docs/analysis_D/tables/D15b_loco_selected_configs.csv
         manuscript_rse/sections/supp_tab_loco_configs.tex (LaTeX table body for the Supplement)
"""
import os
import numpy as np
import pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
LOCO = os.path.join(ROOT, 'outputs', 'benchmarks', 'loco_b1v2')
master = pd.read_csv(os.path.join(LOCO, 'loco_b1v2_master.csv'))

rows = []
for _, m in master.iterrows():
    led = pd.read_csv(os.path.join(LOCO, f'optuna_{m.sensor}_{m.held_out_class}.csv'))
    t = led[led.number == m.best_trial].iloc[0]
    assert t.state == 'COMPLETE', (m.sensor, m.held_out_class)
    assert abs(t.value - m.best_inner_J_hpo) < 1e-9
    done = led[led.state == 'COMPLETE']
    assert abs(done.value.min() - t.value) < 1e-12, 'selected trial is not the study minimum'
    for p, c in [('input_mode', 'cfg_input_mode'), ('hidden_dim', 'cfg_hidden_dim'), ('n_layers', 'cfg_n_layers'),
                 ('activation', 'cfg_activation'), ('lr', 'cfg_lr'), ('w_sam', 'cfg_w_sam'), ('w_grad', 'cfg_w_grad'),
                 ('w_curve', 'cfg_w_curve'), ('w_phys', 'cfg_w_phys')]:
        a, b = t['params_' + p], m[c]
        assert (a == b) if isinstance(b, str) else abs(float(a) - float(b)) < 1e-12, (m.sensor, m.held_out_class, p, a, b)
    rows.append(dict(sensor=m.sensor, held_out_class=m.held_out_class, best_trial=int(t.number),
                     n_complete=int(len(done)), n_pruned=int((led.state == 'PRUNED').sum()), inner_J=float(t.value),
                     best_epoch=int(m.best_epoch), input_mode=t.params_input_mode, n_layers=int(t.params_n_layers),
                     hidden_dim=int(t.params_hidden_dim), activation=t.params_activation, dropout=float(t.params_dropout),
                     optimizer=t.params_optimizer_name, lr=float(t.params_lr),
                     weight_decay=(float(t.params_weight_decay) if not pd.isna(t.params_weight_decay) else np.nan),
                     batch_size=int(t.params_batch_size), w_eps=float(t.params_w_mse_eps), w_sam=float(t.params_w_sam),
                     w_grad=float(t.params_w_grad), w_curv=float(t.params_w_curve), w_phys=float(t.params_w_phys),
                     n_inner_train_spectra=int(m.n_inner_train_spectra), n_inner_val_spectra=int(m.n_inner_val_spectra),
                     n_group_purged=int(m.n_group_purged)))
df = pd.DataFrame(rows)
df.to_csv(os.path.join(ROOT, 'docs', 'analysis_D', 'tables', 'D15b_loco_selected_configs.csv'), index=False)
print(df.round(5).to_string())


def sci(x):
    if pd.isna(x):
        return '--'
    e = int(np.floor(np.log10(abs(x))))
    return f'${x / 10 ** e:.2f}\\times10^{{{e}}}$'


cls = {'botanical': 'Bot.', 'soil': 'Soil', 'sandstone': 'Sand.', 'quartz': 'Qtz.'}
cols = [(r.sensor, r.held_out_class) for r in df.itertuples()]
head = ' & '.join(f'{"AST" if s == "aster" else "HyT"} {cls[c]}' for s, c in cols)
spec = [('Selected trial (complete/pruned)', lambda r: f'{r.best_trial} ({r.n_complete}/{r.n_pruned})'),
        ('Inner $\\mathcal{J}$ (HPO)', lambda r: f'{r.inner_J:.3f}'),
        ('Best epoch (of 100)', lambda r: f'{r.best_epoch}'),
        ('Ingestion', lambda r: r.input_mode),
        ('Layers $\\times$ units', lambda r: f'{r.n_layers}$\\times${r.hidden_dim}'),
        ('Activation', lambda r: r.activation),
        ('Dropout', lambda r: f'{r.dropout:.3f}'),
        ('Optimizer', lambda r: r.optimizer),
        ('Learning rate', lambda r: sci(r.lr)),
        ('Weight decay', lambda r: sci(r.weight_decay) if r.optimizer == 'AdamW' else '--'),
        ('Batch size', lambda r: f'{r.batch_size}'),
        ('$w_{\\varepsilon}$', lambda r: f'{r.w_eps:.3f}'),
        ('$w_{\\mathrm{sam}}$', lambda r: f'{r.w_sam:.3f}'),
        ('$w_{\\mathrm{grad}}$', lambda r: f'{r.w_grad:.3f}'),
        ('$w_{\\mathrm{curv}}$', lambda r: sci(r.w_curv)),
        ('$w_{\\mathrm{phys}}$', lambda r: sci(r.w_phys)),
        ('Inner train / val spectra', lambda r: f'{r.n_inner_train_spectra}/{r.n_inner_val_spectra}'),
        ('Purged spectra', lambda r: f'{r.n_group_purged}')]
lines = ['% AUTO-GENERATED by scripts/analysis/export_loco_configs_B1v2.py -- do not edit by hand.',
         '\\begin{tabular}{l' + 'c' * len(cols) + '}', '\\toprule', 'Hyperparameter & ' + head + ' \\\\', '\\midrule']
lines += [name + ' & ' + ' & '.join(f(r) for r in df.itertuples()) + ' \\\\' for name, f in spec]
lines += ['\\bottomrule', '\\end{tabular}']
out = os.path.join(ROOT, 'manuscript', 'sections', 'supp_tab_loco_configs.tex')
open(out, 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
print('->', out)

